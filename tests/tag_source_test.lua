package.path = "./?.lua;./?/init.lua;" .. package.path

-- Bank Tags is independent: no dependency injection or import registration.
local Harness = require("tools/test_support/search_harness")
local Json = require("resources/core/json")
local h = Harness.new("without_banktags")
local manifestFile = assert(io.open(h.built.folder .. "/plugin.json", "rb"))
local manifest = Json.decode(manifestFile:read("a"))
manifestFile:close()
assert(manifest.version == "1.0.0" and manifest.dependencies == nil)
assert(manifest.requiredDependencies.prettyui == 6398181)
assert(manifest.requiredDependencies.bankcore == 6464293)
assert(manifest.requiredDependencies.runeql == 6464301)
assert(manifest.requiredDependencies.gepl == 6414886)
assert(manifest.requiredDependencies.geprices == nil)
assert(manifest.requiredDependencies.banktags == nil and manifest.optionalDependencies.banktags == nil)
local registrations = 0
h.host.exports.banktags = { RegisterExtension = function() registrations = registrations + 1 end }
h:NameObjects({ { 101, "Iron bar" } })
h.bankHost:SetItems({ { 101, 5 } })
h:LoadCore()
h:LoadRuneQL()
h:LoadSearch()
local app = h:App()
h:OpenBank()
h:Tick(2)
assert(app.tagSource == nil and app.enabled.banktags == nil)
app:SetText("iron")
assert(app:ShownPage() == "search")
local saved, record = app.queries:Save(nil, "Iron", "iron")
assert(saved and app:ChooseQuery(record.id) and app:ShownPage() == "query")
h.host:Notify("banktags", true, true)
h.host:Notify("banktags", false, false)
assert(app:ShownPage() == "query" and registrations == 0)
h.host:Unload("advancedbanksearch")
h.host:Unload("bankcore")
assert(h:LoggedFailure() == nil, tostring(h:LoggedFailure()))
print("tag_source_test: ok (Bank Tags integration removed)")
